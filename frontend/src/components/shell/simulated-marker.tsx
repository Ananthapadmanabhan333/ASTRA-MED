import { FlaskConical } from "lucide-react";

import { Tooltip, TooltipContent, TooltipTrigger } from "@/components/ui/tooltip";
import { cn } from "@/lib/utils";

/**
 * Persistent reminder that nothing on screen is a real measurement. It is part of the shell,
 * so it can never be scrolled away or omitted from a page.
 */
export function SimulatedMarker({ className }: { className?: string }) {
  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <span
          tabIndex={0}
          className={cn(
            "inline-flex items-center gap-1.5 rounded-full border border-dashed border-caution/60 px-2.5 py-1 text-xs font-medium text-caution",
            className,
          )}
        >
          <FlaskConical className="size-3.5" aria-hidden />
          Simulated data
        </span>
      </TooltipTrigger>
      <TooltipContent side="bottom" className="max-w-xs text-pretty">
        Every value is generated by the ASTRA-MED simulator for fictional crew. This is a research
        prototype, not a medical device, and it is not clinically validated.
      </TooltipContent>
    </Tooltip>
  );
}

export function SimulatedNote({ children, className }: { children?: React.ReactNode; className?: string }) {
  return (
    <p className={cn("flex items-center gap-1.5 text-xs text-ink-3", className)}>
      <FlaskConical className="size-3" aria-hidden />
      {children ?? "Simulated data"}
    </p>
  );
}
