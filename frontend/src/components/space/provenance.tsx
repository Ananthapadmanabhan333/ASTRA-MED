export function CategoryBadge({ category, className }: { category: DataCategory; className?: string }) {
  const c = CATEGORY[category];
  const Icon = c.icon;
  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <span
          tabIndex={0}
          className={cn("inline-flex items-center gap-1 rounded-full border px-2 py-0.5 text-[11px] font-medium whitespace-nowrap", c.cls, className)}
        >
          <Icon className="size-3" aria-hidden />
          {c.label}
        </span>
      </TooltipTrigger>
      <TooltipContent side="bottom" className="max-w-xs text-pretty">
        {c.help}
      </TooltipContent>
    </Tooltip>
  );
}

const MODE: Record<FreshnessMode, { label: string; icon: LucideIcon; cls: string }> = {
  live: { label: "NASA data, synchronised", icon: Satellite, cls: "text-nominal" },
  cached: { label: "NASA data, stored copy", icon: Database, cls: "text-ink-2" },
  "offline-fallback": { label: "NASA source offline: stored copy", icon: CloudOff, cls: "text-caution" },
  unavailable: { label: "NASA source unavailable", icon: CloudOff, cls: "text-critical" },
  pending: { label: "Waiting for first sync", icon: RefreshCw, cls: "text-ink-3" },
};

export function FreshnessBadge({ freshness, className }: { freshness: Freshness | undefined; className?: string }) {
  const zone = useDisplayZone((s) => s.zone);
  if (!freshness) return null;
  const m = MODE[freshness.mode];
  const Icon = m.icon;
  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <span tabIndex={0} className={cn("inline-flex items-center gap-1.5 text-xs", m.cls, className)}>
          <Icon className="size-3.5" aria-hidden />
          {m.label}
          {freshness.retrieved_at && (
            <span className="text-ink-3">
              · retrieved {inZone(freshness.retrieved_at, zone, "datetime", true)}
            </span>
          )}
        </span>
      </TooltipTrigger>
      <TooltipContent side="bottom" className="max-w-xs text-pretty">
        {freshness.message}
      </TooltipContent>
    </Tooltip>
  );
}

export function SourceLine({ children, href, className }: { children: React.ReactNode; href?: string; className?: string }) {
  return (
    <p className={cn("text-xs text-ink-3", className)}>
      Source:{" "}
      {href ? (
        <a href={href} target="_blank" rel="noreferrer" className="underline decoration-dotted underline-offset-2 hover:text-ink-2">
          {children}
        </a>
      ) : (
        children
      )}
    </p>
  );
}

export function ZoneSelect({ className }: { className?: string }) {
  const zone = useDisplayZone((s) => s.zone);
  const setZone = useDisplayZone((s) => s.setZone);
  useEffect(() => hydrateZone(), []);
  return (
    <Select value={zone} onValueChange={(v) => setZone(v as ZoneValue)}>
      <SelectTrigger size="sm" className={cn("w-48", className)} aria-label="Display timezone">
        <SelectValue />
      </SelectTrigger>
      <SelectContent>
        {ZONES.map((z) => (
          <SelectItem key={z.value} value={z.value}>
            {z.label}
          </SelectItem>
        ))}
      </SelectContent>
    </Select>
  );
}

/** Formats a UTC instant in the selected display zone. */
export function When({ iso, kind = "datetime", suffix = true }: { iso: string | null | undefined; kind?: "datetime" | "date" | "time"; suffix?: boolean }) {
  const zone = useDisplayZone((s) => s.zone);
  useEffect(() => hydrateZone(), []);
  if (!iso) return <span className="text-ink-3">—</span>;
  return (
    <time dateTime={iso} title={`${iso} (UTC)`}>{inZone(iso, zone, kind, suffix)}</time>
  );
}
