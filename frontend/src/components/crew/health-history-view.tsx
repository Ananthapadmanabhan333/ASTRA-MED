"use client";

import { Download, Fingerprint, History, Moon, Search, UserCheck } from "lucide-react";
import Link from "next/link";
import { Suspense, useState } from "react";
import { toast } from "sonner";

import { Panel } from "@/components/data/panel";
import { EmptyState, LoadingState, QueryView } from "@/components/data/states";
import { CrewPicker, KindChip, SimulatedBanner, useParamState } from "@/components/medical/common";
import { Button } from "@/components/ui/button";
import { HistoryPanel } from "@/components/vitals/history-panel";
import { useAstronauts, useSleep } from "@/lib/api/hooks";
import { useTwin, useTwinTimeline } from "@/lib/api/medical-hooks";
import type { TwinDay } from "@/lib/api/types";
import { fmt, utcDay } from "@/lib/format";

function metricMean(d: TwinDay, key: string): number | null {
  const m = d.metrics[key] as { awake_rest_mean?: number; mean?: number } | undefined;
  return m?.awake_rest_mean ?? m?.mean ?? null;
}

function HealthHistoryInner() {
  const crew = useAstronauts();
  const [param, setParam] = useParamState("astronaut");
  const [daySearch, setDaySearch] = useState("");
  const [daysWindow, setDaysWindow] = useState<number>(30);
  const aid = param ?? crew.data?.[0]?.id ?? "AST-01";
  const astronaut = crew.data?.find((a) => a.id === aid);
  const twin = useTwin(aid);
  const timeline = useTwinTimeline(aid, daysWindow);
  const sleep = useSleep(aid, 14);

  function exportCsv() {
    const days = timeline.data?.days ?? [];
    if (!days.length) {
      toast.error("No daily records loaded yet to export.");
      return;
    }
    const headers = [
      "day",
      "mission_day",
      "basis",
      "hr_awake_rest",
      "spo2_awake_rest",
      "temp_c",
      "resp_rate",
      "sleep_hours",
      "sleep_eff_pct",
      "dose_msv",
    ];
    const lines = [
      headers.join(","),
      ...days.map((d) => {
        const sl = d.sleep as { duration_hours?: number; efficiency_pct?: number } | null;
        const rad = d.radiation as { dose_msv?: number } | null;
        return [
          d.day,
          d.mission_day,
          d.basis,
          metricMean(d, "heart_rate") ?? "",
          metricMean(d, "spo2") ?? "",
          metricMean(d, "temperature_c") ?? "",
          metricMean(d, "respiratory_rate") ?? "",
          sl?.duration_hours ?? "",
          sl?.efficiency_pct ?? "",
          rad?.dose_msv ?? "",
        ].join(",");
      }),
    ];
    const blob = new Blob([lines.join("\n")], { type: "text/csv;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `astra-med-health-history-${aid}-${daysWindow}d.csv`;
    a.click();
    setTimeout(() => URL.revokeObjectURL(url), 10_000);
    toast.success(`Exported ${days.length} daily records for ${astronaut?.name ?? aid}`);
  }

  const filteredDays = (timeline.data?.days ?? []).filter((d) => {
    if (!daySearch.trim()) return true;
    const q = daySearch.toLowerCase();
    return (
      d.day.toLowerCase().includes(q) ||
      `day ${d.mission_day}`.includes(q) ||
      d.basis.toLowerCase().includes(q) ||
      d.stage.toLowerCase().includes(q)
    );
  });

  return (
    <div className="space-y-5">
      <div className="flex flex-wrap items-end justify-between gap-4">
        <div>
          <h1 className="flex items-center gap-2 font-heading text-3xl font-bold tracking-tight">
            <History className="size-7 text-telemetry" aria-hidden />
            Detailed Astronaut Health History
          </h1>
          <p className="text-sm text-ink-2">
            High-resolution vital-sign time series, longitudinal daily summaries, sleep architecture and exportable
            records
          </p>
        </div>
        <div className="flex flex-wrap items-center gap-2">
          <Button variant="outline" size="sm" onClick={exportCsv}>
            <Download className="size-4" aria-hidden /> Export CSV
          </Button>
          <Button asChild variant="outline" size="sm">
            <Link href={`/twin?astronaut=${aid}`}>
              <Fingerprint className="size-4 text-telemetry" aria-hidden /> Digital Twin
            </Link>
          </Button>
          <Button asChild variant="outline" size="sm">
            <Link href={`/self-check?astronaut=${aid}`}>
              <UserCheck className="size-4 text-telemetry" aria-hidden /> Self-Check
            </Link>
          </Button>
        </div>
      </div>

      <SimulatedBanner>
        All historical physiological measurements, sleep sessions and daily summaries are generated by the ASTRA-MED
        physiological simulator and labelled <code>simulated</code>.
      </SimulatedBanner>

      <div className="flex flex-wrap items-center justify-between gap-3 rounded-xl border border-bulkhead bg-hull p-3.5">
        <CrewPicker value={aid} onChange={(v) => setParam(v)} />
        {twin.data && (
          <div className="flex flex-wrap gap-5 text-xs text-ink-2">
            <span>
              Role: <strong className="text-foreground">{twin.data.astronaut.role}</strong>
            </span>
            <span>
              Coverage: <strong className="text-foreground">{twin.data.coverage.days_total} mission days</strong> (
              {twin.data.coverage.days_stored} stored / {twin.data.coverage.days_regenerated} regenerated)
            </span>
            <span>
              Stage: <strong className="text-telemetry">{twin.data.mission.stage.label}</strong>
            </span>
          </div>
        )}
      </div>

      {/* Synchronized High-Resolution Vitals Charts */}
      <HistoryPanel astronautId={aid} name={astronaut?.name ?? aid} />

      {/* Longitudinal Daily Health Log */}
      <Panel
        raised
        title={`Longitudinal Daily Health Log (${astronaut?.name ?? aid})`}
        description="Awake-at-rest daily means, sleep duration, efficiency, radiation dose and alert counts per mission day."
        actions={
          <div className="flex flex-wrap items-center gap-2">
            <div className="relative">
              <Search className="pointer-events-none absolute top-2 left-2.5 size-3.5 text-ink-3" aria-hidden />
              <input
                type="search"
                placeholder="Filter by date, day or stage..."
                aria-label="Filter daily records"
                value={daySearch}
                onChange={(e) => setDaySearch(e.target.value)}
                className="h-7 w-48 rounded-md border border-input bg-abyss pr-2 pl-7 text-xs outline-none focus-visible:border-telemetry"
              />
            </div>
            <div className="flex rounded-md border border-bulkhead bg-abyss p-0.5 text-xs">
              {[14, 30, 60].map((w) => (
                <button
                  key={w}
                  type="button"
                  onClick={() => setDaysWindow(w)}
                  className={`rounded px-2 py-0.5 font-medium ${daysWindow === w ? "bg-telemetry text-[#04131c]" : "text-ink-2 hover:text-foreground"}`}
                >
                  {w}d
                </button>
              ))}
            </div>
          </div>
        }
      >
        <QueryView query={timeline}>
          {() =>
            filteredDays.length === 0 ? (
              <EmptyState title="No matching daily records" />
            ) : (
              <div className="max-h-96 overflow-auto">
                <table className="w-full min-w-[780px] text-left text-xs">
                  <thead className="sticky top-0 bg-hull text-ink-2">
                    <tr className="border-b border-bulkhead">
                      <th className="py-2 pr-3 font-medium">Date (UTC)</th>
                      <th className="py-2 pr-3 font-medium">Mission Day</th>
                      <th className="py-2 pr-3 font-medium">Basis</th>
                      <th className="py-2 pr-3 font-medium">Resting HR</th>
                      <th className="py-2 pr-3 font-medium">Resting SpO₂</th>
                      <th className="py-2 pr-3 font-medium">Temp</th>
                      <th className="py-2 pr-3 font-medium">Resp. Rate</th>
                      <th className="py-2 pr-3 font-medium">Sleep</th>
                      <th className="py-2 pr-3 font-medium">Efficiency</th>
                      <th className="py-2 font-medium">Dose</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-bulkhead/40 tabular-nums">
                    {[...filteredDays].reverse().map((d) => {
                      const sl = d.sleep as { duration_hours?: number; efficiency_pct?: number } | null;
                      const rad = d.radiation as { dose_msv?: number } | null;
                      return (
                        <tr key={d.day} className="hover:bg-panel-2/50">
                          <td className="py-2 pr-3 font-medium text-foreground">{utcDay(d.day)}</td>
                          <td className="py-2 pr-3 text-ink-2">Day {d.mission_day}</td>
                          <td className="py-2 pr-3">
                            <KindChip kind={d.category} />
                          </td>
                          <td className="py-2 pr-3 text-telemetry">
                            {fmt(metricMean(d, "heart_rate"), 1)} bpm
                          </td>
                          <td className="py-2 pr-3">{fmt(metricMean(d, "spo2"), 1)}%</td>
                          <td className="py-2 pr-3">{fmt(metricMean(d, "temperature_c"), 2)}°C</td>
                          <td className="py-2 pr-3">{fmt(metricMean(d, "respiratory_rate"), 1)}/min</td>
                          <td className="py-2 pr-3">{fmt(sl?.duration_hours ?? null, 1)} h</td>
                          <td className="py-2 pr-3">{fmt(sl?.efficiency_pct ?? null, 0)}%</td>
                          <td className="py-2">{fmt(rad?.dose_msv ?? null, 2)} mSv</td>
                        </tr>
                      );
                    })}
                  </tbody>
                </table>
              </div>
            )
          }
        </QueryView>
      </Panel>

      {/* Sleep & Circadian History */}
      <Panel
        title="Sleep & Circadian Architecture (Last 14 Nights)"
        description="Nightly sleep duration, efficiency and schedule onset offset."
        actions={<Moon className="size-4 text-telemetry" aria-hidden />}
      >
        <QueryView query={sleep}>
          {(sessions) => {
            const avgDur = sessions.length
              ? sessions.reduce((a, x) => a + x.duration_hours, 0) / sessions.length
              : null;
            const avgEff = sessions.length
              ? sessions.reduce((a, x) => a + x.efficiency_pct, 0) / sessions.length
              : null;
            const avgOffset = sessions.length
              ? sessions.reduce((a, x) => a + Math.abs(x.onset_offset_minutes), 0) / sessions.length
              : null;
            return (
              <div className="space-y-3">
                <div className="grid grid-cols-2 gap-3 sm:grid-cols-4">
                  <div className="rounded-lg border border-bulkhead/70 bg-abyss/60 p-3">
                    <p className="text-xs text-ink-3">Mean Duration</p>
                    <p className="readout mt-1 text-2xl font-semibold text-telemetry">
                      {fmt(avgDur, 1)} <span className="text-xs text-ink-3">h</span>
                    </p>
                  </div>
                  <div className="rounded-lg border border-bulkhead/70 bg-abyss/60 p-3">
                    <p className="text-xs text-ink-3">Mean Efficiency</p>
                    <p className="readout mt-1 text-2xl font-semibold text-nominal">
                      {fmt(avgEff, 0)} <span className="text-xs text-ink-3">%</span>
                    </p>
                  </div>
                  <div className="rounded-lg border border-bulkhead/70 bg-abyss/60 p-3">
                    <p className="text-xs text-ink-3">Mean Onset Drift</p>
                    <p className="readout mt-1 text-2xl font-semibold text-caution">
                      {fmt(avgOffset, 0)} <span className="text-xs text-ink-3">min</span>
                    </p>
                  </div>
                  <div className="rounded-lg border border-bulkhead/70 bg-abyss/60 p-3">
                    <p className="text-xs text-ink-3">Nights Recorded</p>
                    <p className="readout mt-1 text-2xl font-semibold text-foreground">{sessions.length}</p>
                  </div>
                </div>
              </div>
            );
          }}
        </QueryView>
      </Panel>
    </div>
  );
}

export function HealthHistoryView() {
  return (
    <Suspense fallback={<LoadingState rows={6} />}>
      <HealthHistoryInner />
    </Suspense>
  );
}
