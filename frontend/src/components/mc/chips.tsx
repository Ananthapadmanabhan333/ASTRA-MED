"use client";

import { Cpu, FlaskConical, Radio, Satellite, Server, type LucideIcon } from "lucide-react";

import { Tooltip, TooltipContent, TooltipTrigger } from "@/components/ui/tooltip";
import type { DataOrigin, EventSeverity } from "@/lib/api/types";
import { cn } from "@/lib/utils";

const PRIORITY: Record<number, { label: string; cls: string; help: string }> = {
  1: { label: "Critical", cls: "border-critical bg-critical text-[#2a0606]", help: "Rule-based detection of a critical value. Act now." },
  2: { label: "High", cls: "border-caution/70 bg-caution/12 text-caution", help: "Needs attention soon." },
  3: { label: "Medium", cls: "border-advisory/60 bg-advisory/10 text-advisory", help: "Review when possible. Experimental AI output never ranks above this." },
  4: { label: "Low", cls: "border-ink-3/50 text-ink-2", help: "Informational." },
};

/** P1-P4 on the shared scale. Always number and word, never colour alone. */
export function PriorityBadge({ priority, className, compact = false }: { priority: number; className?: string; compact?: boolean }) {
  const p = PRIORITY[priority] ?? PRIORITY[4];
  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <span
          tabIndex={0}
          className={cn(
            "inline-flex shrink-0 items-center gap-1 rounded-md border px-1.5 py-px text-[11px] font-semibold whitespace-nowrap tabular-nums",
            p.cls,
            className,
          )}
        >
          P{priority}
          {!compact && <span className="font-medium">{p.label}</span>}
        </span>
      </TooltipTrigger>
      <TooltipContent side="bottom" className="max-w-xs text-pretty">
        Priority {priority} ({p.label}). {p.help}
      </TooltipContent>
    </Tooltip>
  );
}

const ORIGIN: Record<DataOrigin, { label: string; icon: LucideIcon; cls: string; help: string }> = {
  simulated: {
    label: "Simulated",
    icon: FlaskConical,
    cls: "border-telemetry/35 text-telemetry",
    help: "From the continuous simulated crew stream. Crew members are fictional.",
  },
  sandbox: {
    label: "Sandbox",
    icon: FlaskConical,
    cls: "border-sandbox/60 text-sandbox",
    help: "From a mission simulation sandbox run. Isolated from the crew stream; not live data.",
  },
  nasa: {
    label: "NASA data",
    icon: Satellite,
    cls: "border-nominal/45 text-nominal",
    help: "Real NASA open data (DONKI). An environmental indicator, never a crew dose.",
  },
  system: { label: "Platform", icon: Server, cls: "border-ink-3/50 text-ink-2", help: "Generated by the platform itself." },
};

/** Where a value comes from: the simulated crew stream, the sandbox, or real NASA data. */
export function OriginChip({ origin, className }: { origin: DataOrigin; className?: string }) {
  const o = ORIGIN[origin] ?? ORIGIN.system;
  const Icon = o.icon;
  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <span
          tabIndex={0}
          className={cn(
            "inline-flex shrink-0 items-center gap-1 rounded-full border px-1.5 py-px text-[11px] font-medium whitespace-nowrap",
            o.cls,
            className,
          )}
        >
          <Icon className="size-3" aria-hidden />
          {o.label}
        </span>
      </TooltipTrigger>
      <TooltipContent side="bottom" className="max-w-xs text-pretty">{o.help}</TooltipContent>
    </Tooltip>
  );
}

/** Marks experimental model output wherever it appears. */
export function ExperimentalTag({ className }: { className?: string }) {
  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <span
          tabIndex={0}
          className={cn(
            "inline-flex shrink-0 items-center gap-1 rounded-full border border-dashed border-advisory/60 px-1.5 py-px text-[11px] font-medium text-advisory",
            className,
          )}
        >
          <Cpu className="size-3" aria-hidden />
          Experimental AI
        </span>
      </TooltipTrigger>
      <TooltipContent side="bottom" className="max-w-xs text-pretty">
        Model output trained on simulated data. A prompt for review by qualified personnel, not a confirmed medical
        emergency or a diagnosis.
      </TooltipContent>
    </Tooltip>
  );
}

const SEV_DOT: Record<EventSeverity, string> = {
  info: "bg-ink-3",
  advisory: "bg-advisory",
  caution: "bg-caution",
  critical: "bg-critical",
};

export function SeverityDot({ severity, className }: { severity: EventSeverity; className?: string }) {
  return <span className={cn("inline-block size-2 shrink-0 rounded-full", SEV_DOT[severity], className)} aria-hidden />;
}

/** Amber test-range tape label for anything that belongs to the simulation sandbox. */
export function SandboxTag({ className, children }: { className?: string; children?: React.ReactNode }) {
  return (
    <span
      className={cn(
        "inline-flex shrink-0 items-center gap-1.5 overflow-hidden rounded-md border border-sandbox/60 bg-sandbox/10 pr-2 text-[11px] font-semibold text-sandbox",
        className,
      )}
    >
      <span className="sandbox-tape h-full w-2 self-stretch opacity-80" aria-hidden />
      {children ?? "Sandbox"}
    </span>
  );
}

export function LivePulse({ className }: { className?: string }) {
  return (
    <span className={cn("relative inline-flex size-2", className)} aria-hidden>
      <span className="absolute inline-flex size-full animate-ping rounded-full bg-telemetry/50 motion-reduce:hidden" />
      <span className="relative inline-flex size-2 rounded-full bg-telemetry" />
    </span>
  );
}

export function RadioIcon(props: { className?: string }) {
  return <Radio {...props} aria-hidden />;
}
