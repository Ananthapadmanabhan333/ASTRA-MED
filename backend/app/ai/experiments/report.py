"""Render an experiment's results.json as a markdown evaluation report."""

from __future__ import annotations

from typing import Any


def _f(v: Any, nd: int = 3) -> str:
    if v is None:
        return "n/a"
    if isinstance(v, float):
        return f"{v:.{nd}f}"
    return str(v)


def _pct(v: Any) -> str:
    return "n/a" if v is None else f"{100 * v:.0f}%"


def render_report(r: dict[str, Any]) -> str:
    ds, an, fc = r["dataset"], r["anomaly"], r["forecast"]
    lines: list[str] = [
        f"# ASTRA-MED model evaluation: {r['version']}",
        "",
        "> **Synthetic data only.** Every result below comes from data generated by the ASTRA-MED simulator. "
        "It measures how well each method recovers the simulator's injected events and dynamics. It does "
        "**not** establish clinical or real-world predictive accuracy, and no model here is validated on "
        "astronaut or patient populations.",
        "",
        f"Generated {r['created_at']} from commit `{r.get('git_commit') or 'unknown'}` in {r['runtime_seconds']} s "
        f"(Python {r['environment']['python']}).",
        "",
        "## Dataset",
        "",
        f"- Source: {ds['source']}. Real data: {ds['real_data']}.",
        f"- Fingerprint `{ds['fingerprint']}`: {ds['samples']:,} samples at {ds['interval_minutes']}-minute "
        f"resolution for {len(ds['crew'])} crew members over {ds['config']['days']} days (seed {ds['config']['seed']}).",
        f"- Events: {ds['events']['total']} ({ds['events']['sudden']} sudden, {ds['events']['gradual']} gradual, "
        f"{ds['events']['subtle']} subtle). Missing rate {_pct(ds['defects']['missing_rate'])}, "
        f"{ds['defects']['artefacts']} artefact spikes (not anomalies).",
        "",
        "| Split | Windows | Anomalous windows | From | To |",
        "| --- | --- | --- | --- | --- |",
    ]
    for part, s in ds["splits"].items():
        lines.append(f"| {part} | {s['windows']:,} | {_pct(s['label_rate'])} | {s['start'][:16]} | {s['end'][:16]} |")
    lines += [
        "",
        "Splits are chronological and day-aligned. Baselines and scalers are fitted on clean training "
        "windows only; features are causal; forecast targets never cross a split boundary.",
        "",
        "## Anomaly detection",
        "",
        f"Detectors train on {an['train_windows']:,} clean training windows. Each threshold is set on "
        f"validation normal windows for a {_pct(an['target_false_alarm_rate'])} false-alarm rate, then "
        f"applied once to {an['test_windows']:,} test windows (anomalous rate {_pct(an['test_label_rate'])}; "
        f"{an['ambiguous_test_windows_excluded']} ramp-edge windows below the label level are excluded).",
        "",
        "| Model | Precision | Recall | F1 | AUROC | AUPRC | False-alarm rate | Events detected | Sudden | Gradual | Subtle | Median delay |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    rows = {**{k: v for k, v in an["models"].items() if "test" in v}, "ensemble": an["ensemble"], "fixed_thresholds": an["fixed_thresholds"]}
    for m in rows.values():
        t, e = m["test"], m["events"]
        kinds = e.get("by_kind", {})
        lines.append(
            f"| {m['label']} | {_f(t['precision'])} | {_f(t['recall'])} | {_f(t['f1'])} | {_f(t['auroc'])} | "
            f"{_f(t['auprc'])} | {_f(t['false_alarm_rate'], 4)} | {_pct(e['event_recall'])} | "
            f"{_pct(kinds.get('sudden', {}).get('recall'))} | {_pct(kinds.get('gradual', {}).get('recall'))} | "
            f"{_pct(m['events_by_intensity'].get('subtle', {}).get('recall'))} | {_f(e['median_delay_min'], 0)} min |"
        )
    lines += [
        "",
        "Operational view (a warning needs 2 consecutive flagged windows, i.e. 10 minutes):",
        "",
        "| Model | False warnings per crew-day | Events warned |",
        "| --- | --- | --- |",
    ]
    for m in rows.values():
        o = m["operational"]
        lines.append(f"| {m['label']} | {_f(o['false_warnings_per_crew_day'], 2)} | {_pct(o['event_recall'])} |")
    lines += ["", f"Ensemble members ({an['ensemble'].get('member_rule', '')}): "
              + ", ".join(f"{k} {v:.3f}" for k, v in an["ensemble"]["weights"].items()), ""]
    lines += ["Selected feature sets: " + ", ".join(
        f"{k} = {v.get('selected_features')}" for k, v in an["models"].items() if "selected_features" in v), ""]

    lines += ["### Detection by event type (ensemble)", "", "| Event type | Events | Detected | Median delay |", "| --- | --- | --- | --- |"]
    for etype, v in sorted(an["ensemble"]["events_by_type"].items()):
        lines.append(f"| {etype} | {v['events']} | {_pct(v['recall'])} | {_f(v['median_delay_min'], 0)} min |")

    if an.get("ablations"):
        lines += [
            "", "### Feature-set selection and ablation", "",
            "Each learned detector was fitted on every candidate feature set. The set with the best "
            "**validation** AUPRC was kept (marked *selected*); the test columns are reported for the "
            "ablation study only and played no part in the choice.", "",
            "| Detector | Feature set | n | Val AUPRC | Test AUROC | Test F1 | Events | Sudden | Gradual |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
        ]
        for det, block in an["ablations"].items():
            for cand, v in block["candidates"].items():
                mark = f"**{cand}** (selected)" if cand == block["selected"] else cand
                t = v["test"]
                lines.append(
                    f"| {det} | {mark} | {v['n_features']} | {_f(v['val_auprc'])} | {_f(t['auroc'])} | {_f(t['f1'])} | "
                    f"{_pct(t['event_recall'])} | {_pct(t['sudden_recall'])} | {_pct(t['gradual_recall'])} |"
                )

    lines += [
        "",
        "## Forecasting",
        "",
        f"30-minute steps, {fc['lookback_hours']} h of history, horizons {', '.join(f'{h} h' for h in fc['horizons_hours'])}. "
        f"Samples: {fc['samples']['train']:,} train, {fc['samples']['early_stopping']:,} early-stopping, "
        f"{fc['samples']['calibration']:,} conformal calibration, {fc['samples']['test']:,} test. "
        f"Intervals are split-conformal at {_pct(fc['interval_nominal_coverage'])} nominal coverage.",
        "",
    ]
    units = {"heart_rate": "bpm", "spo2": "%", "respiratory_rate": "breaths/min", "temperature_c": "°C"}
    for sig, unit in units.items():
        lines += [f"### {sig.replace('_', ' ').capitalize()} ({unit})", "",
                  "| Model | " + " | ".join(f"MAE {h}h | RMSE {h}h | Coverage {h}h" for h in fc["horizons_hours"]) + " | Skill vs climatology 1h / 24h |",
                  "| --- | " + " | ".join("--- | --- | ---" for _ in fc["horizons_hours"]) + " | --- |"]
        for name, m in fc["models"].items():
            if "by_signal" not in m:
                lines.append(f"| {name} | skipped: {m.get('skipped')} |")
                continue
            s = m["by_signal"][sig]
            cells = " | ".join(f"{_f(s[f'{h}h']['mae'])} | {_f(s[f'{h}h']['rmse'])} | {_pct(s[f'{h}h'].get('coverage'))}" for h in fc["horizons_hours"])
            skill = m.get("skill_vs_climatology", {}).get(sig, {})
            lines.append(f"| {m['label']} | {cells} | {_f(skill.get('1h'), 2)} / {_f(skill.get('24h'), 2)} |")
        lines.append("")

    if fc.get("ablations"):
        lines += ["### Ablation: XGBoost feature groups (MAE)", "",
                  "| Variant | HR 1h | HR 24h | SpO2 1h | SpO2 24h | Temp 1h | Temp 24h |", "| --- | --- | --- | --- | --- | --- | --- |"]
        full = fc["models"].get("xgboost", {}).get("by_signal")
        if full:
            lines.append(f"| full model | {_f(full['heart_rate']['1h']['mae'])} | {_f(full['heart_rate']['24h']['mae'])} | "
                         f"{_f(full['spo2']['1h']['mae'])} | {_f(full['spo2']['24h']['mae'])} | "
                         f"{_f(full['temperature_c']['1h']['mae'])} | {_f(full['temperature_c']['24h']['mae'])} |")
        for name, a in fc["ablations"].items():
            m = a["mae"]
            lines.append(f"| {name} | {_f(m['heart_rate']['1h'])} | {_f(m['heart_rate']['24h'])} | {_f(m['spo2']['1h'])} | "
                         f"{_f(m['spo2']['24h'])} | {_f(m['temperature_c']['1h'])} | {_f(m['temperature_c']['24h'])} |")
        lines.append("")

    shap = fc.get("xgboost_shap_importance", {}).get("heart_rate", {})
    if shap:
        lines += ["### What drives the XGBoost heart-rate forecast (mean |SHAP| share)", "", "| Feature group | 1 h | 24 h |", "| --- | --- | --- |"]
        for group in shap.get("1h", {}):
            lines.append(f"| {group} | {_pct(shap['1h'].get(group))} | {_pct(shap.get('24h', {}).get(group))} |")
        lines.append("")

    lines += ["## Limitations", ""] + [f"- {x}" for x in r["limitations"]] + [""]
    return "\n".join(lines)
